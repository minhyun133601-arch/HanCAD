/**
 * Command flags mirror ObjectARX command registration flags. Lists follow Autodesk
 * documentation where it states the behavior; the remainder is recorded in
 * docs/DECISIONS.md and docs/PARITY_CHECKLIST.md for reference verification.
 */
const words = (value: string): ReadonlySet<string> => new Set(value.trim().split(/\s+/));

