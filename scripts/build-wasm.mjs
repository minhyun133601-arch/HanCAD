import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { access, copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { delimiter, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const cargoBin = join(homedir(), '.cargo', 'bin');
const env = { ...process.env, PATH: `${cargoBin}${delimiter}${process.env.PATH ?? ''}` };
const cargoPath = join(cargoBin, process.platform === 'win32' ? 'cargo.exe' : 'cargo');
const cargo = existsSync(cargoPath) ? cargoPath : 'cargo';

const adapterSource = `// Generated by scripts/build-wasm.mjs. Do not edit.
let kernel;
let loading;

export default async function init(options = {}) {
  if (kernel) return kernel;
  if (loading) return loading;
  loading = (async () => {
    const source = options.module_or_path ?? new URL('geometry_wasm_bg.wasm', import.meta.url);
    const bytes = source instanceof URL
      ? await (await fetch(source)).arrayBuffer()
      : source;
    const result = await WebAssembly.instantiate(bytes, {});
    const exports = result instanceof WebAssembly.Instance ? result.exports : result.instance.exports;
    for (const name of ['distance2d', 'midpoint_x2d', 'midpoint_y2d']) {
      if (typeof exports[name] !== 'function') throw new Error('Missing WASM geometry export: ' + name);
    }
    kernel = exports;
    return kernel;
  })();
  try {
    return await loading;
  } catch (error) {
    loading = undefined;
    throw error;
  }
}

function initialized() {
  if (!kernel) throw new Error('Geometry WASM has not been initialized.');
  return kernel;
}

export function distance2d(ax, ay, bx, by) {
  return initialized().distance2d(ax, ay, bx, by);
}

export function midpoint2d(ax, ay, bx, by) {
  const exports = initialized();
  return new Float64Array([exports.midpoint_x2d(ax, bx), exports.midpoint_y2d(ay, by)]);
}
`;

const adapterTypes = `// Generated by scripts/build-wasm.mjs. Do not edit.
export interface InitOptions {
  module_or_path?: BufferSource | WebAssembly.Module;
}
export default function init(options?: InitOptions): Promise<WebAssembly.Exports>;
export function distance2d(ax: number, ay: number, bx: number, by: number): number;
export function midpoint2d(ax: number, ay: number, bx: number, by: number): Float64Array;
`;

function run(command, args, capture = false) {
  const result = spawnSync(command, args, {
    cwd: root,
    env,
    stdio: capture ? 'pipe' : 'inherit',
    encoding: 'utf8',
    windowsHide: true,
  });
  if (result.error) throw new Error(`${command}: ${result.error.message}`);
  if (result.status !== 0) {
    throw new Error(`${command} exited ${result.status}: ${result.stderr ?? ''}`);
  }
  return result.stdout?.trim() ?? '';
}

try {
  const output = join(root, 'packages', 'geom', 'wasm');
  await mkdir(output, { recursive: true });
  run(cargo, [
    'build',
    '--locked',
    '-p',
    'hancad-geometry-wasm',
    '--release',
    '--target',
    'wasm32-unknown-unknown',
  ]);
  const wasm = join(
    root,
    'target',
    'wasm32-unknown-unknown',
    'release',
    'hancad_geometry_wasm.wasm',
  );
  await access(wasm);
  await copyFile(wasm, join(output, 'geometry_wasm_bg.wasm'));
  await writeFile(join(output, 'geometry_wasm.js'), adapterSource);
  await writeFile(join(output, 'geometry_wasm.d.ts'), adapterTypes);

  const module = await import(pathToFileURL(join(output, 'geometry_wasm.js')).href);
  await module.default({ module_or_path: await readFile(join(output, 'geometry_wasm_bg.wasm')) });
  assert.equal(module.distance2d(1, 2, 4, 6), 5);
  assert.deepEqual(Array.from(module.midpoint2d(1, 2, 4, 6)), [2.5, 4]);
  const translation = 200_000_000;
  assert.equal(
    module.distance2d(translation + 1, translation + 2, translation + 4, translation + 6),
    5,
  );
  assert.deepEqual(
    Array.from(
      module.midpoint2d(Number.MAX_VALUE, Number.MAX_VALUE, Number.MAX_VALUE, Number.MAX_VALUE),
    ),
    [Number.MAX_VALUE, Number.MAX_VALUE],
  );
  console.log('WASM round trip passed: distance=5, midpoint=[2.5,4].');
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
